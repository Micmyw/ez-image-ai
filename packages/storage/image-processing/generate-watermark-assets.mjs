import { writeFile } from "node:fs/promises";

import sharp from "sharp";

// Regenerate only when the EzPic plate design changes. This build-time script
// preserves the existing SVG artwork; runtime Workers import only PNG bytes.
const width = 720;
const height = 216;
const fontSize = Math.max(12, Math.round(height * 0.48));
const radius = Math.max(4, Math.round(height * 0.18));
const plateSvg = `<svg width="${width}" height="${height}" xmlns="http://www.w3.org/2000/svg"><rect width="${width}" height="${height}" rx="${radius}" fill="#111827" fill-opacity="0.72"/></svg>`;
const textSvg = `<svg width="${width}" height="${height}" xmlns="http://www.w3.org/2000/svg"><text x="50%" y="52%" dominant-baseline="middle" text-anchor="middle" fill="#ffffff" font-family="Arial, sans-serif" font-size="${fontSize}" font-weight="700" letter-spacing="0.5">EzPic</text></svg>`;
const plate = await sharp(Buffer.from(plateSvg)).png({ compressionLevel: 9 }).toBuffer();
const text = await sharp(Buffer.from(textSvg))
	.trim()
	.png({ compressionLevel: 9 })
	.toBuffer({ resolveWithObject: true });
await writeFile(
	new URL("./watermark-assets.ts", import.meta.url),
	`// Generated by generate-watermark-assets.mjs from the existing EzPic plate.\nexport const GUEST_WATERMARK_PNG = {\n\tplate: "${plate.toString("base64")}",\n\ttext: "${text.data.toString("base64")}",\n} as const;\nexport const GUEST_WATERMARK_TEXT = { width: ${text.info.width}, height: ${text.info.height}, fontSize: ${fontSize} } as const;\n`,
);
